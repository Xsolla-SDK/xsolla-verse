export const STRINGS = { en, es, ja }

export function translate(lang, path) {
  const table = STRINGS[lang] || STRINGS.en
  const fallback = STRINGS.en
  const parts = path.split('.')
  let cur = table
  let fb = fallback
  for (const p of parts) {
    cur = cur && cur[p]
    fb = fb && fb[p]
  }
  return cur || fb || path
}
